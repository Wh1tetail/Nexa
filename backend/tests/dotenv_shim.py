"""Minimal .env loader for tests (pydantic-settings reads .env itself, but we need
DATABASE_URL in os.environ before deriving the test database URL)."""
import os
from pathlib import Path


def load_env() -> None:
    path = Path(__file__).resolve().parents[1] / ".env"
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        os.environ.setdefault(k.strip(), v.strip())


load_env()
