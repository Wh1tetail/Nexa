"""PreToolUse hook: block Edit/Write on secrets (.env) and npm lock files.

Exit code 2 blocks the tool call; the stderr text is shown to Claude.
`.env.example` stays editable — it is the documented template.
"""
import json
import sys
from pathlib import PurePath

BLOCKED_EXACT = {"package-lock.json"}
ALLOWED_ENV = {".env.example"}


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        return 0
    path = (payload.get("tool_input") or {}).get("file_path") or ""
    name = PurePath(path.replace("\\", "/")).name
    if name in BLOCKED_EXACT:
        print(f"Blocked: {name} is generated by npm - change dependencies with `npm install` instead.", file=sys.stderr)
        return 2
    if (name == ".env" or name.startswith(".env.")) and name not in ALLOWED_ENV:
        print(
            f"Blocked: {path} holds environment secrets. "
            "Edit .env.example instead and ask the user to update their .env.",
            file=sys.stderr,
        )
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
